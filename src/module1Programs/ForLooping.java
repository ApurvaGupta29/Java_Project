package module1Programs;

public class ForLooping {

	public static void main(String[] args)

	{
		System.out.println("Start of the loop");

		for (int i = -3; i < 3; i++) {
			System.out.println("Apurva");
		}

		System.out.println("End of the loop");

		/*
		 * i=0,true,Logic i=1,true,Logic i=2,true,Logic i=3,false if condition is wrong
		 * it will come out of the loop. it will not terminate
		 */

	}

}
